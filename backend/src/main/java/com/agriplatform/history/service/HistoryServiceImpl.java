package com.agriplatform.history.service;

import com.agriplatform.common.exception.ResourceNotFoundException;
import com.agriplatform.common.util.SecurityUtils;
import com.agriplatform.cultivation.entity.CultivationIntentionHistory;
import com.agriplatform.cultivation.entity.CultivationStatusEvent;
import com.agriplatform.cultivation.repository.CultivationHistoryRepository;
import com.agriplatform.cultivation.repository.CultivationIntentionRepository;
import com.agriplatform.cultivation.repository.CultivationStatusEventRepository;
import com.agriplatform.farmer.entity.FarmerProfile;
import com.agriplatform.farmer.repository.FarmerProfileRepository;
import com.agriplatform.history.dto.HistorySnapshotDto;
import com.agriplatform.history.dto.HistoryStatusEventDto;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.data.domain.Page;
import org.springframework.data.domain.Pageable;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;

import java.util.Arrays;
import java.util.Collections;
import java.util.List;
import java.util.UUID;

/**
 * Task 09 — History Service implementation.
 *
 * <h2>Architecture</h2>
 * <p>This service provides <strong>READ-ONLY</strong> access to the two
 * immutable audit tables generated by DB triggers:
 * <ul>
 *   <li>{@code public.cultivation_intention_history} (field-change snapshots)</li>
 *   <li>{@code public.cultivation_status_events} (status lifecycle events)</li>
 * </ul>
 * No INSERT, UPDATE, or DELETE operations are performed here or in any
 * repository called by this service.
 *
 * <h2>Identity and IDOR</h2>
 * <p>Farmer identity is derived exclusively from the JWT {@code sub} claim
 * via {@link SecurityUtils#getAuthenticatedUserId()}.
 * Every query filters by {@code farmer_id} to prevent cross-farmer leakage.
 *
 * <h2>History Generation</h2>
 * <p>History records are created by PostgreSQL triggers:
 * <ul>
 *   <li>{@code trg_record_intention_history} — fires AFTER UPDATE on
 *       cultivation_intentions, writes the OLD row to history</li>
 *   <li>{@code trg_record_status_event_insert} — fires AFTER INSERT,
 *       captures the initial PLANNED event</li>
 *   <li>{@code trg_record_status_event_update} — fires AFTER UPDATE
 *       when status changes</li>
 * </ul>
 * Application code NEVER writes to these tables.
 */
@Service
@Transactional(readOnly = true)
public class HistoryServiceImpl implements HistoryService {

    private static final Logger log = LoggerFactory.getLogger(HistoryServiceImpl.class);

    private final CultivationHistoryRepository historyRepository;
    private final CultivationStatusEventRepository statusEventRepository;
    private final CultivationIntentionRepository cultivationRepository;
    private final FarmerProfileRepository farmerProfileRepository;
    private final SecurityUtils securityUtils;

    public HistoryServiceImpl(
            CultivationHistoryRepository historyRepository,
            CultivationStatusEventRepository statusEventRepository,
            CultivationIntentionRepository cultivationRepository,
            FarmerProfileRepository farmerProfileRepository,
            SecurityUtils securityUtils) {
        this.historyRepository = historyRepository;
        this.statusEventRepository = statusEventRepository;
        this.cultivationRepository = cultivationRepository;
        this.farmerProfileRepository = farmerProfileRepository;
        this.securityUtils = securityUtils;
    }

    // =========================================================================
    // HISTORY SNAPSHOTS
    // =========================================================================

    @Override
    public Page<HistorySnapshotDto> getSnapshotsForCultivation(UUID cultivationId, Pageable pageable) {
        UUID farmerId = securityUtils.getAuthenticatedUserId();
        requireFarmerExists(farmerId);
        verifyOwnership(cultivationId, farmerId);

        log.debug("getSnapshotsForCultivation: cultivationId={}, farmerId={}", cultivationId, farmerId);
        Page<CultivationIntentionHistory> page =
                historyRepository.findAllByIntentionIdOrderByVersionDesc(cultivationId, pageable);
        return page.map(this::toSnapshotDto);
    }

    @Override
    public HistorySnapshotDto getSnapshot(UUID cultivationId, UUID historyId) {
        UUID farmerId = securityUtils.getAuthenticatedUserId();
        requireFarmerExists(farmerId);

        CultivationIntentionHistory record =
                historyRepository.findByHistoryIdAndIntentionIdAndFarmerId(historyId, cultivationId, farmerId)
                        .orElseThrow(() -> new ResourceNotFoundException(
                                "History snapshot not found with id: " + historyId));

        log.debug("getSnapshot: historyId={}, cultivationId={}, farmerId={}", historyId, cultivationId, farmerId);
        return toSnapshotDto(record);
    }

    // =========================================================================
    // STATUS EVENTS
    // =========================================================================

    @Override
    public Page<HistoryStatusEventDto> getStatusEventsForCultivation(UUID cultivationId, Pageable pageable) {
        UUID farmerId = securityUtils.getAuthenticatedUserId();
        requireFarmerExists(farmerId);
        verifyOwnership(cultivationId, farmerId);

        log.debug("getStatusEventsForCultivation: cultivationId={}, farmerId={}", cultivationId, farmerId);
        Page<CultivationStatusEvent> page =
                statusEventRepository.findAllByIntentionIdOrderByChangedAtAsc(cultivationId, pageable);
        return page.map(this::toStatusEventDto);
    }

    // =========================================================================
    // MAPPERS
    // =========================================================================

    private HistorySnapshotDto toSnapshotDto(CultivationIntentionHistory h) {
        List<String> changedFields = h.getChangedFields() != null
                ? Arrays.asList(h.getChangedFields())
                : Collections.emptyList();
        return new HistorySnapshotDto(
                h.getHistoryId(),
                h.getIntentionId(),
                h.getVersion(),
                h.getSnapshotAt(),
                h.getPlotId(),
                h.getFarmerId(),
                h.getCropId(),
                h.getCropVarietyId(),
                h.getSeasonId(),
                h.getCultivationYear(),
                h.getCultivatedAreaAcres(),
                h.getPlannedPlantingDate(),
                h.getActualPlantingDate(),
                h.getActualAreaAcres(),
                h.getHarvestDate(),
                h.getStatus(),
                h.getStatusReason(),
                h.getSource(),
                h.getActorId(),
                h.getActorType(),
                h.getChangeType(),
                changedFields,
                h.getChangeReason()
        );
    }

    private HistoryStatusEventDto toStatusEventDto(CultivationStatusEvent e) {
        return new HistoryStatusEventDto(
                e.getId(),
                e.getIntentionId(),
                e.getFromStatus(),
                e.getToStatus(),
                e.getChangedBy(),
                e.getActorType(),
                e.getChangedAt(),
                e.getNote()
        );
    }

    // =========================================================================
    // GUARDS
    // =========================================================================

    /**
     * Verifies the cultivation intention exists AND belongs to the authenticated farmer.
     * Returns HTTP 404 for any mismatch (IDOR protection — no 403 to prevent enumeration).
     */
    private void verifyOwnership(UUID cultivationId, UUID farmerId) {
        if (!cultivationRepository.existsByIdAndFarmerId(cultivationId, farmerId)) {
            throw new ResourceNotFoundException(
                    "Cultivation intention not found with id: " + cultivationId);
        }
    }

    /**
     * Verifies the farmer profile exists and is not deleted.
     * Suspended farmers can still READ history (read-only access, no data modification).
     */
    private void requireFarmerExists(UUID farmerId) {
        FarmerProfile farmer = farmerProfileRepository.findByIdWithGeography(farmerId)
                .orElseThrow(() -> new ResourceNotFoundException(
                        "Farmer profile not found for user: " + farmerId));
        if (FarmerProfile.STATUS_DELETED.equals(farmer.getProfileStatus())) {
            throw new ResourceNotFoundException("Farmer profile not found for user: " + farmerId);
        }
    }
}
